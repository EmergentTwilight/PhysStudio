"""Thermal conservation, rigid motion, phase topology, and trajectory checks."""
import argparse
import json
from pathlib import Path
import numpy as np
from scipy.spatial import cKDTree
from scipy.spatial.transform import Rotation
import warp as wp
from .thermal import LATENT,CP_ICE,CP_WATER,temperature,fraction
from . import thermal
from .solver import IceSystem,density,normals,surface_forces,wall_film_viscosity


def config(dx):
    return dict(dx=dx,mass=917.*dx**3,bounds=[[-1.,-1.,-1.],[1.,1.,1.]],air_t=0.,air_h=0.,
        plate_t=0.,plate_h=0.,radiant=0.,spot=[0.,0.,0.],spot_width=.1,thermal_scale=1.)


def numerics(device,check_bunny=False):
    wp.init();dx=.003
    x=np.array([[0.,0.,.1],[dx,0.,.1]],np.float32)
    e=np.array([-10.*CP_ICE,LATENT+20.*CP_WATER],np.float32)
    system=IceSystem(x,np.array([0,-1],np.int32),e,config(dx),device)
    system.grid.build(system.x,system.h)
    system.launch(thermal.rate,2,[system.x,system.e,system.grid.id,system.h,system.norm,dx,system.mass,
        0.,0.,0.,0.,0.,wp.vec3(0.),.1,system.heat_rate,system.external,system.thermal_diag])
    rates=system.heat_rate.numpy().astype(float);flux=rates*system.mass
    symmetry=abs(flux.sum())/max(abs(flux).sum(),1.e-12)
    assert symmetry<2.e-6 and rates[0]>0 and rates[1]<0,(symmetry,rates)
    for _ in range(200):system.heat(.01)
    heat_balance=abs(float(system.e.numpy().astype(float).sum()-e.astype(float).sum()))/LATENT
    assert heat_balance<2.e-5,heat_balance
    assert temperature(system.e.numpy()).min()>=-10.001 and temperature(system.e.numpy()).max()<=20.001

    # A known heat input must first warm the solid, then pay the full latent heat.
    value=wp.array([-2100.],dtype=float,device=device)
    rate=wp.array([1000.],dtype=float,device=device);ext=wp.array([1.],dtype=float,device=device)
    ledger=wp.zeros(1,dtype=float,device=device)
    temps=[];energies=[]
    for _ in range(400):
        wp.launch(thermal.integrate,1,inputs=[value,rate,ext,ledger,1.],device=device)
        q=float(value.numpy()[0]);energies.append(q);temps.append(float(temperature(q)))
    energies=np.array(energies);temps=np.array(temps)
    assert np.all(temps[(energies>=0)&(energies<=LATENT)]==0.)
    assert np.all(temps[energies>LATENT]>0.) and energies[-1]==397900.

    # Best-fit rigid projection preserves pair distances and center of mass.
    rest=np.stack(np.meshgrid(np.arange(4)*dx,np.arange(3)*dx,np.arange(3)*dx,indexing='ij'),-1).reshape(-1,3).astype(np.float32)
    cfg=config(dx);g=np.zeros(len(rest),np.int32)
    rigid=IceSystem(rest,g,np.full(len(rest),-2100.,np.float32),cfg,device)
    rotation=Rotation.from_euler('xyz',[27,-15,63],degrees=True).as_matrix()
    posed=rest@rotation.T+np.array([.02,.03,.10]);rigid.x.assign(posed.astype(np.float32));rigid.shape_match()
    actual=rigid.x.numpy();fit_error=float(np.max(np.linalg.norm(actual-posed,axis=1)))
    assert fit_error<2.e-6,fit_error

    # Large bodies must remain at rest despite repeated parallel pose reductions.
    from .scenes import build
    ax,ag,ae,acfg=build('arch')
    resting=IceSystem(ax,ag,ae,acfg,device)
    for _ in range(60):resting.step(1/1440,7,heating=False)
    settled=resting.x.numpy()
    for _ in range(240):resting.step(1/1440,7,heating=False)
    rest_drift=float(np.linalg.norm(resting.x.numpy()-settled,axis=1).max())
    rest_speed=float(np.linalg.norm(resting.v.numpy(),axis=1).max())
    assert rest_drift<1.e-5 and rest_speed<1.e-3,(rest_drift,rest_speed)

    # An open scan must not silently turn into a resolution-dependent shell.
    masses=[];volume_difference=None
    if check_bunny:
        for spacing in [.0022,.0016]:
            bx,_,_,bcfg=build('bunny',spacing)
            masses.append(len(bx)*bcfg['mass'])
        volume_difference=abs(masses[0]-masses[1])/masses[1]
        assert .15<masses[1]<.25 and volume_difference<.10,(masses,volume_difference)

    # Removing the sole thermal bridge splits the remaining rest graph in two.
    left=np.array([[i,j,k] for i in [0,1,2] for j in [0,1] for k in [1,2]],np.float32)*dx
    right=left+np.array([4*dx,0.,0.]);bridge=np.array([[3*dx,0.,dx]],np.float32)
    x=np.vstack([left,right,bridge]);e=np.full(len(x),-2100.,np.float32)
    split=IceSystem(x,np.zeros(len(x),np.int32),e,cfg,device)
    e[-1]=LATENT;split.e.assign(e);split.update_components()
    assert split.group_count==2 and split.groups.numpy()[-1]==-1

    # Isolate constraint convergence from velocity generated by the initial overlap.
    p=np.stack(np.meshgrid(*[np.arange(7)*dx*.78]*3,indexing='ij'),-1).reshape(-1,3).astype(np.float32)
    fluid=IceSystem(p,np.full(len(p),-1,np.int32),np.full(len(p),LATENT+10*CP_WATER,np.float32),cfg,device)
    fluid.grid.build(fluid.x,fluid.h)
    fluid.launch(density,fluid.n,[fluid.x,fluid.e,fluid.groups,fluid.grid.id,fluid.h,fluid.norm,fluid.lam,fluid.rho])
    before=float(np.max(fluid.rho.numpy()))
    for _ in range(8):
        fluid.step(1/1440,8,heating=False)
        fluid.v.zero_()
    after=float(np.max(fluid.rho.numpy()))
    assert before>1.5 and .95<after<1.10,(before,after)
    fluid.grid.build(fluid.x,fluid.h);fluid.v.zero_()
    fluid.launch(normals,fluid.n,[fluid.x,fluid.e,fluid.groups,fluid.grid.id,fluid.h,fluid.norm,fluid.normal])
    fluid.launch(surface_forces,fluid.n,[fluid.x,fluid.v,fluid.vout,fluid.e,fluid.groups,fluid.normal,fluid.rho,
        fluid.grid.id,fluid.h,fluid.norm,fluid.mass,1/1440,.025,.035,.25,12.])
    impulses=fluid.vout.numpy().astype(float)
    momentum=float(np.linalg.norm(impulses.sum(0))/max(np.linalg.norm(impulses,axis=1).sum(),1.e-15))
    assert momentum<2.e-6,momentum

    # Film drag dissipates energy only near the wall, leaving ice and distant water unchanged.
    radius=.46*dx;depth=2.*dx
    positions=np.array([[0,0,radius],[dx,0,radius+depth/2],
        [2*dx,0,radius+depth],[3*dx,0,radius]],np.float32)
    initial_v=np.tile([.8,-.3,.2],(4,1)).astype(np.float32)
    velocity=wp.array(initial_v,dtype=wp.vec3,device=device)
    phase=wp.array([LATENT,LATENT,LATENT,-2100.],dtype=float,device=device)
    groups=wp.array([-1,-1,-1,0],dtype=int,device=device)
    wp.launch(wall_film_viscosity,4,inputs=[wp.array(positions,dtype=wp.vec3,device=device),
        velocity,phase,groups,0.,radius,depth,80.,.001],device=device)
    damped=velocity.numpy()
    np.testing.assert_allclose(damped[:2],initial_v[:2]/np.array([[1.08],[1.02]]),rtol=2.e-6)
    np.testing.assert_array_equal(damped[2:],initial_v[2:])
    assert np.sum(damped*damped)<np.sum(initial_v*initial_v)

    # The flattened Gaussian changes shape, but preserves its integrated water volume.
    from .surface import deposit,film_shape
    ds=.15*dx;origin=np.array([-4.*dx,-4.*dx,radius-4.*dx])
    shape=(55,55,55);ice_field=wp.zeros(shape,dtype=float,device=device)
    water_field=wp.zeros(shape,dtype=float,device=device)
    particle=wp.array([[0.,0.,radius]],dtype=wp.vec3,device=device)
    phase=wp.array([LATENT],dtype=float,device=device);integrals=[]
    flatness=wp.ones(1,dtype=float,device=device)
    for wetting in [0,1]:
        water_field.zero_()
        wp.launch(deposit,1,inputs=[particle,phase,ice_field,water_field,wp.vec3(*origin),ds,dx,0.,wetting,flatness],device=device)
        integrals.append(float(water_field.numpy().astype(float).sum()*ds**3/(.917*dx**3)))
    assert all(.96<v<1.01 for v in integrals),integrals
    assert abs(integrals[0]-integrals[1])<.005,integrals

    # A deeper pool must not retain stacked, flattened particle layers.
    film=np.array([[i*dx,j*dx,radius] for i in range(-3,4) for j in range(-3,4)],np.float32)
    grid=wp.HashGrid(32,32,32,device=device);flatness_checks=[]
    for layers in [1,3]:
        points=np.concatenate([film+np.array([0,0,k*dx]) for k in range(layers)]).astype(np.float32)
        points=wp.array(points,dtype=wp.vec3,device=device)
        phase=wp.full(len(points),LATENT,dtype=float,device=device)
        flat=wp.zeros(len(points),dtype=float,device=device);grid.build(points,3.*dx)
        wp.launch(film_shape,len(points),inputs=[points,phase,grid.id,dx,flat],device=device)
        flatness_checks.append(float(flat.numpy()[24]))
    np.testing.assert_allclose(flatness_checks,[1.,0.],atol=1.e-5)
    return dict(heat_pair_relative_imbalance=symmetry,isolated_heat_relative_error=heat_balance,
        latent_plateau='passed',bunny_voxel_mass_kg=masses,bunny_relative_volume_difference=volume_difference,
        large_body_rest_drift_m=rest_drift,large_body_rest_speed_m_s=rest_speed,rigid_fit_error_m=fit_error,thermal_split_components=split.group_count,
        compressed_density_before=before,compressed_density_after=after,surface_force_momentum_error=momentum,
        local_film_drag='passed',water_kernel_integrals=integrals,thin_and_deep_pool_flatness=flatness_checks)


def trajectory(path):
    cfg=json.loads((path/'config.json').read_text());audit=json.loads((path/'audit.json').read_text())
    initial=np.load(path/'initial.npz');n=cfg['particles'];mass=cfg['mass'];dx=cfg['dx']
    frames=sorted((path/'states').glob('*.npz'));assert len(frames)==cfg['frames']==len(audit)
    cold=np.flatnonzero(initial['groups']>=0);pairs=cold[cKDTree(initial['positions'][cold]).query_pairs(1.45*dx,output_type='ndarray')]
    rest_distance=np.linalg.norm(initial['positions'][pairs[:,0]]-initial['positions'][pairs[:,1]],axis=1)
    strain=0.;floor_gap=1.;speed=0.;energy_error=0.;last_time=-1.;remaining=[]
    for file,row in zip(frames,audit):
        with np.load(file) as state:
            for key in state.files:assert np.isfinite(state[key]).all(),(file,key)
            assert state['positions'].shape==(n,3)
            assert float(state['time'])>last_time;last_time=float(state['time'])
            active=(state['enthalpy']<LATENT)&(state['groups']>=0)
            edges=active[pairs[:,0]]&active[pairs[:,1]]&(state['groups'][pairs[:,0]]==state['groups'][pairs[:,1]])
            if edges.any():
                p=pairs[edges];d=np.linalg.norm(state['positions'][p[:,0]]-state['positions'][p[:,1]],axis=1)
                strain=max(strain,float(np.max(abs(d/rest_distance[edges]-1.))))
            floor_gap=min(floor_gap,float(state['positions'][:,2].min()-.46*dx))
            speed=max(speed,float(np.linalg.norm(state['velocities'],axis=1).max()))
            remaining.append(int(active[cold].sum()))
        energy_error=max(energy_error,abs(row['energy_balance_J'])/max(abs(row['external_heat_J']),n*mass*LATENT))
    assert strain<.003,strain
    assert floor_gap>-2.e-6,floor_gap
    assert energy_error<2.e-4,energy_error
    assert abs(last_time-cfg['seconds'])<1.e-6
    assert remaining[-1]<=remaining[0]
    if not cfg.get('heating',True):
        assert remaining[-1]==remaining[0]
    return dict(scene=cfg['scene'],frames=len(frames),particles=n,mass_kg=n*mass,
        final_mobile_fraction_of_initial_ice=1.-remaining[-1]/len(cold),max_rigid_edge_strain=strain,
        minimum_floor_gap_m=floor_gap,max_speed_m_s=speed,max_advective_cfl=speed*cfg['dt']/dx,
        maximum_relative_energy_error=energy_error,final_components=audit[-1]['solid_components'])


def meshes(path):
    files=sorted(path.glob('*.npz'));assert files
    maximum=0
    for file in files:
        with np.load(file) as mesh:
            for name in ['ice','water']:
                v=mesh[name+'_vertices'];f=mesh[name+'_faces'];assert np.isfinite(v).all()
                if len(f):
                    assert f.min()>=0 and f.max()<len(v)
                    tri=v[f].astype(float)
                    volume=np.einsum('ij,ij->i',tri[:,0],np.cross(tri[:,1],tri[:,2])).sum()/6.
                    assert volume>0.,(file,name,volume)
                    maximum=max(maximum,len(f))
    return dict(frames=len(files),outward_winding='passed',max_triangles=maximum)


def main():
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True)
    p.add_argument('--device',default='cuda:0');p.add_argument('--simulations',nargs='*',type=Path,default=[])
    p.add_argument('--meshes',nargs='*',type=Path,default=[]);p.add_argument('--skip-numerics',action='store_true')
    p.add_argument('--check-bunny',action='store_true',help='Check solid filling of the downloaded bunny')
    args=p.parse_args();report=dict(status='passed')
    check_bunny=args.check_bunny or any(json.loads((path/'config.json').read_text())['scene']=='bunny' for path in args.simulations)
    if not args.skip_numerics:report['numerics']=numerics(args.device,check_bunny)
    report['trajectories']=[trajectory(p) for p in args.simulations];report['meshes']=[meshes(p) for p in args.meshes]
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(report,indent=2))
    print(json.dumps(report,indent=2))


if __name__=='__main__':main()
